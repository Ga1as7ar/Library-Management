#!/usr/bin/env python3
"""Bundle assets/icons/*.svg (Tabler Icons, MIT) into one SVG sprite for the web UI.

Usage: python3 tools/build_icon_sprite.py
Each icon becomes <symbol id="i-NAME">; reference it with <svg><use href="icons.svg#i-NAME"/></svg>.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "assets" / "icons"
TARGET = ROOT / "web" / "public" / "icons.svg"


def symbol(path: Path) -> str:
    svg = path.read_text(encoding="utf-8")
    body = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S).group(1)
    body = re.sub(r'<path stroke="none" d="M0 0h24v24H0z" fill="none"\s*/>', "", body)
    body = " ".join(body.split())
    return f'<symbol id="i-{path.stem}" viewBox="0 0 24 24">{body}</symbol>'


def main() -> None:
    symbols = "\n".join(symbol(p) for p in sorted(SOURCE.glob("*.svg")))
    TARGET.write_text(
        '<svg xmlns="http://www.w3.org/2000/svg" style="display:none">\n'
        f"<!-- Generated by tools/build_icon_sprite.py from Tabler Icons (MIT). Do not edit. -->\n{symbols}\n</svg>\n",
        encoding="utf-8",
    )
    print(f"wrote {TARGET.relative_to(ROOT)} ({len(list(SOURCE.glob('*.svg')))} icons)")


if __name__ == "__main__":
    main()
